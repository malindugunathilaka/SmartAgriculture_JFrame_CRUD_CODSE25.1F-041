    private void loadFarmerData() {
        tableModel.setRowCount(0);
        List<Farmer> farmers = FarmerDAO.getAllFarmers();
        for (Farmer farmer : farmers) {
            Object[] row = {
                farmer.getFarmerId(),
                farmer.getFarmerName(),
                farmer.getNic(),
                farmer.getAddress(),
                farmer.getContactNo()
            };
            tableModel.addRow(row);
        }
    }

    private void clearForm() {
        txtFarmerId.setText("");
        txtFarmerName.setText("");
        txtNIC.setText("");
        txtAddress.setText("");
        txtContactNo.setText("");
        tblFarmers.clearSelection();
        txtFarmerName.requestFocus();
    }

    private boolean validateInput() {
        if (txtFarmerName.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Farmer name is required!", "Validation Error", JOptionPane.ERROR_MESSAGE);
            txtFarmerName.requestFocus();
            return false;
        }
        if (txtNIC.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "NIC is required!", "Validation Error", JOptionPane.ERROR_MESSAGE);
            txtNIC.requestFocus();
            return false;
        }
        return true;
    }

