    private void tblFarmersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblFarmersMouseClicked
        int selectedRow = tblFarmers.getSelectedRow();
        if (selectedRow >= 0) {
            txtFarmerId.setText(tableModel.getValueAt(selectedRow, 0).toString());
            txtFarmerName.setText(tableModel.getValueAt(selectedRow, 1).toString());
            txtNIC.setText(tableModel.getValueAt(selectedRow, 2).toString());
            txtAddress.setText(tableModel.getValueAt(selectedRow, 3) != null ? tableModel.getValueAt(selectedRow, 3).toString() : "");
            txtContactNo.setText(tableModel.getValueAt(selectedRow, 4) != null ? tableModel.getValueAt(selectedRow, 4).toString() : "");
        }
    }//GEN-LAST:event_tblFarmersMouseClicked

