    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        if (!validateInput()) return;
        
        if (FarmerDAO.isNicExists(txtNIC.getText().trim())) {
            JOptionPane.showMessageDialog(this, "NIC already exists!", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        Farmer farmer = new Farmer(
            txtFarmerName.getText().trim(),
            txtNIC.getText().trim(),
            txtAddress.getText().trim(),
            txtContactNo.getText().trim()
        );
        
        if (FarmerDAO.insertFarmer(farmer)) {
            JOptionPane.showMessageDialog(this, "Farmer saved successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            clearForm();
            loadFarmerData();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to save farmer!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (txtFarmerId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a farmer to update!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!validateInput()) return;
        
        Farmer farmer = new Farmer();
        farmer.setFarmerId(Integer.parseInt(txtFarmerId.getText()));
        farmer.setFarmerName(txtFarmerName.getText().trim());
        farmer.setNic(txtNIC.getText().trim());
        farmer.setAddress(txtAddress.getText().trim());
        farmer.setContactNo(txtContactNo.getText().trim());
        
        if (FarmerDAO.updateFarmer(farmer)) {
            JOptionPane.showMessageDialog(this, "Farmer updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            clearForm();
            loadFarmerData();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update farmer!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txtFarmerId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a farmer to delete!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this farmer?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            if (FarmerDAO.deleteFarmer(Integer.parseInt(txtFarmerId.getText()))) {
                JOptionPane.showMessageDialog(this, "Farmer deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                clearForm();
                loadFarmerData();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to delete farmer!", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

